"""Rebuild INDEX.md: every solved problem, sorted by number, with the file it lives in.

Usage (from anywhere):  python Storage/LC/gen_index.py

A problem is detected by its banner:
/**
 * =====...
 * 123. Problem Title
 * =====...
 */
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
BANNER_RE = re.compile(r"/\*\*\r?\n \* =+\r?\n \* ((\d+)[^\r\n]*)\r?\n \* =+\r?\n \*/")

rows = []
for root, _, names in os.walk(HERE):
    for name in names:
        if not name.endswith((".cpp", ".js")):
            continue
        path = os.path.join(root, name)
        rel = os.path.relpath(path, HERE).replace(os.sep, "/")
        with open(path, encoding="utf-8") as f:
            text = f.read()
        for m in BANNER_RE.finditer(text):
            line = text.count("\n", 0, m.start()) + 3  # line of the title
            rows.append((int(m.group(2)), m.group(1).strip(), rel, line))

rows.sort(key=lambda r: (r[0], r[2]))

# one row per problem; a problem solved in several files (e.g. C++ and JS) gets several links
problems = {}
for n, title, rel, line in rows:
    num, _, name = title.partition(". ")  # "944 + 955 + 960. Delete ..." -> num / name
    p = problems.setdefault(n, {"num": num, "name": name, "links": []})
    p["links"].append(f"[{rel}](<{rel}#L{line}>)")

out = ["# LeetCode Index", "", f"Solved: **{len(problems)}** problems  ",
       "_Auto-generated by `gen_index.py` - do not edit by hand._", "",
       "| No. | LC # | Problem | File |", "|---:|---:|---|---|"]
for i, (n, p) in enumerate(sorted(problems.items()), 1):
    out.append(f"| {i} | {p['num']} | {p['name']} | {', '.join(p['links'])} |")
with open(os.path.join(HERE, "INDEX.md"), "w", encoding="utf-8", newline="\r\n") as f:
    f.write("\n".join(out) + "\n")
print(f"INDEX.md: {len(problems)} problems ({len(rows)} solutions)")
